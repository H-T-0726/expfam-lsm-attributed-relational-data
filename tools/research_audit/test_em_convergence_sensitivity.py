def _score_row(n, rep, k, start, checkpoint, s1):
    return {"checkpoint_iteration": checkpoint, "n": n, "replicate": rep,
            "k_est": k, "start": start, "heldout_mean_log_score": s1,
            "s2_q_based": -s1, "s3_plugin_conditional": -s1}


def test_start_disagreement_is_false_when_both_starts_choose_the_same_k():
    """Numerically different scores are NOT disagreement (finding H2-02)."""

    rows = [_score_row(50, 1, 2, 1, 8, -0.90), _score_row(50, 1, 2, 2, 8, -0.80),
            _score_row(50, 1, 3, 1, 8, -0.50), _score_row(50, 1, 3, 2, 8, -0.10)]
