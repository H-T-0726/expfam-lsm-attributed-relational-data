def _build_fixture(run_dir: Path, protocol_path: Path, baseline_dir: Path,
                   *, tamper=None) -> dict:
    """A small artifact whose scores are consistent with its archived state.

    The data and masks are the frozen generator's; the state is synthetic but
    the recorded scores are computed FROM that state, so the auditor's
    recomputation has something true to confirm and every mutation test has
    something true to break.
    """

    run_dir.mkdir(parents=True, exist_ok=True)
    body = dict(RUN.protocol_body_from_contract())
    body.update({"n_grid": [FIX_N], "replicates": 1,
                 "candidate_k": list(FIX_K), "max_iter": 8,
                 "checkpoints": list(FIX_LADDER), "baseline_checkpoint": 4,
                 "primary_checkpoint": 8,
                 "expected_long_runs": len(FIX_K) * 2,
                 "expected_checkpoint_rows": len(FIX_K) * 2 * len(FIX_LADDER),
                 "expected_iteration_rows": len(FIX_K) * 2 * 8})
    digest = RUN.canonical_hash(body)
    protocol_path.write_text(
        json.dumps({"status": "DRAFT", "protocol": body}, indent=2,
                   sort_keys=True), encoding="utf-8")
    # What the runner copies into the artifact: the body it used, the hash it
    # recomputed, and where it came from.
    (run_dir / "protocol.json").write_text(
        json.dumps({"experiment_id": RUN.EXPERIMENT_ID,
                    "protocol_source": protocol_path.name,
                    "protocol_source_status": "DRAFT",
                    "protocol_hash": digest, "protocol": body},
                   indent=2, sort_keys=True), encoding="utf-8")

    regen = AUDIT.Regenerator(body)
    rng = np.random.default_rng(2026)
    checkpoint_rows, fit_rows, iteration_rows, archive_rows = [], [], [], []
    states: dict[str, np.ndarray] = {}
    index = 0
    dataset, train, _t, ri, ci, y_test = regen.get(FIX_N, 1)
    train_hash, test_hash = AUDIT.stable_hash(train), AUDIT.stable_hash(_t)

    for k_est in FIX_K:
        for start in (1, 2):
            index += 1
            identity = {
                "fit_index": index, "k_true": 5, "n": FIX_N, "replicate": 1,
                "k_est": k_est, "start": start,
                "data_seed": AUDIT.data_seed(body["data_seed_base"], 5, FIX_N, 1),
                "split_seed": AUDIT.split_seed(body["split_seed_base"], 5, FIX_N, 1),
                "model_seed": AUDIT.model_seed(body["model_seed_base"], 5,
                                               FIX_N, 1, k_est, start),
                "train_mask_hash": train_hash, "test_mask_hash": test_hash,
            }
            trace = [{key: float(rng.uniform(0.001, 0.02))
                      for key in RUN.DIAGNOSTIC_KEYS} for _ in range(8)]
            for step, diag in enumerate(trace, start=1):
                iteration_rows.append({
                    **{k: identity[k] for k in ("fit_index", "k_true", "n",
                                                "replicate", "k_est", "start")},
                    "iteration": step, **diag,
                    "nan_iterations_so_far": 0, "attempt_index": 0})
            params = AUDIT.num_params(k_est, body["d"])
            for iteration in FIX_LADDER:
                z = rng.normal(scale=0.4, size=(FIX_N, k_est))
                z_samples = np.stack(
                    [z + rng.normal(scale=0.01, size=z.shape)
                     for _ in range(body["L"])], axis=2)
                f_mat = rng.normal(scale=0.2, size=(body["d"], k_est))
                sigma = np.eye(body["d"])
                w0, w, var_z = -1.0, 0.5, 1.0
                eta = w0 + w * (z @ z.T)
                s1 = AUDIT.heldout_mean_log_score(y_test, eta[ri, ci])
                q = AUDIT.q_strict(dataset.X, dataset.Y, z_samples, f_mat,
                                   var_z, w0, w, train)
                s2 = -2.0 * q + params * math.log(FIX_N)
                s3 = AUDIT.s3_plugin_conditional(dataset.X, dataset.Y, z, f_mat,
                                                 w0, w, params, FIX_N, train)
                state_key = f"{index:04d}_it{iteration:03d}"
                states[f"{state_key}_Z"] = z
                states[f"{state_key}_Zsamples"] = z_samples
                states[f"{state_key}_F"] = f_mat
                states[f"{state_key}_sigma"] = sigma
                states[f"{state_key}_scalars"] = np.array([w0, w, var_z])
                row = dict(identity)
                row.update({
                    "checkpoint_iteration": iteration,
                    "heldout_mean_log_score": s1, "q_strict": q,
                    "s2_q_based": s2, "s3_plugin_conditional": s3,
                    "num_params": params, "w0_hat": w0, "w_hat": w,
                    "var_z": var_z,
                    "cumulative_runtime_s": float(iteration),
                    "nan_iterations_so_far": 0, "attempt_index": 0,
                    "checkpoint_state_digest": AUDIT.state_digest(z, f_mat, w0, w),
                    "state_key": state_key,
                })
                window = trace[max(0, iteration - 4):iteration]
                for key in RUN.DIAGNOSTIC_KEYS:
                    row[key] = trace[iteration - 1][key]
                    row[f"max_{key}_last4"] = max(d[key] for d in window)
                for tau in body["tau_ladder"]:
                    row[f"budget_stable_gram_{tau:g}"] = bool(
                        row["max_gram_rel_change_last4"] < tau)
                    row[f"budget_stable_eta_y_{tau:g}"] = bool(
                        row["max_eta_y_rel_change_last4"] < tau)
                checkpoint_rows.append(row)
                if iteration == body["baseline_checkpoint"]:
                    archive_rows.append({
                        "k_true": 5, "n": FIX_N, "replicate": 1,
                        "k_est": k_est, "start": start,
                        "data_seed": identity["data_seed"],
                        "split_seed": identity["split_seed"],
                        "model_seed": identity["model_seed"],
                        "heldout_mean_log_score": s1, "q_strict": q,
                        "s2_q_based": s2, "s3_plugin_conditional": s3,
                        "num_params": params, "runtime_s": 1.0})
            fit_rows.append({
                **identity, "max_iter": 8, "actual_iterations": 8,
                "stopping_reason": "fixed_budget", "retry_count": 0,
                "retry_seed": identity["model_seed"], "nan_detected": False,
                "attempts_used": 1, "retry_events": "[]", "runtime_s": 2.0})

    if tamper is not None:
        tamper(checkpoint_rows, fit_rows, iteration_rows, states, archive_rows)

    RUN.write_csv(run_dir / "checkpoint_results.csv", checkpoint_rows,
                  RUN.CHECKPOINT_COLUMNS)
    RUN.write_csv(run_dir / "fit_results.csv", fit_rows, RUN.FIT_COLUMNS)
    RUN.write_csv(run_dir / "iteration_diagnostics.csv", iteration_rows,
                  RUN.ITERATION_COLUMNS)
    np.savez_compressed(run_dir / "checkpoint_states.npz", **states)

    baseline_dir.mkdir(parents=True, exist_ok=True)
    RUN.write_csv(baseline_dir / "fit_results.csv", archive_rows,
                  list(archive_rows[0].keys()))
    (baseline_dir / "protocol.json").write_text(json.dumps(
        {"protocol_hash": RUN.BASELINE_PROTOCOL_HASH}), encoding="utf-8")

    (run_dir / "replication_vs_baseline.json").write_text(json.dumps({
        "checkpoint": body["baseline_checkpoint"], "match": True,
        "compared_rows": len(fit_rows), "mismatch_count": 0}), encoding="utf-8")
    (run_dir / "runinfo.json").write_text(json.dumps({
        "protocol_hash": digest,
        "protocol_source": protocol_path.name,
        "run_code_sha": "d" * 40,
        "working_tree_clean_before": True,
        "wall_clock_seconds": 100.0,
        "environment": {"python": "3.13.14", "numpy": np.__version__,
                        "scipy": "x", "platform": "test", "machine": "test",
                        "blas": {"x": "y"}},
    }), encoding="utf-8")
    return body


