def test_p2_arithmetic_is_exactly_the_frozen_definition():
    """delta = 0.5 * sum over starts of [S1(40) - S1(8)]; starts are averaged."""

    rows = [_score_row(50, 1, 2, 1, 8, -1.00), _score_row(50, 1, 2, 2, 8, -2.00),
            _score_row(50, 1, 2, 1, 40, -0.50), _score_row(50, 1, 2, 2, 40, -1.00),
            _score_row(50, 1, 3, 1, 8, -1.00), _score_row(50, 1, 3, 2, 8, -1.00),
            _score_row(50, 1, 3, 1, 40, -1.25), _score_row(50, 1, 3, 2, 40, -1.75)]
    p2, summary = AUDIT._compute_p2(AUDIT.Audit(), rows, (50,), 1, (2, 3),
                                    (1, 2), 8, 40)
    got = {r["k_est"]: r["delta"] for r in p2}
    assert got[2] == pytest.approx(0.5 * ((-0.50 - -1.00) + (-1.00 - -2.00)))
    assert got[2] == pytest.approx(0.75)
    assert got[3] == pytest.approx(0.5 * ((-1.25 - -1.00) + (-1.75 - -1.00)))
    assert got[3] == pytest.approx(-0.5)
    assert {r["k_est"]: r["mean_delta"] for r in summary}[2] == pytest.approx(0.75)
    assert all(r["replicates"] == 1 for r in summary)


